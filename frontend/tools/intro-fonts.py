"""Build one small woff2 per weight holding only the characters this page uses, and write fonts.css.
Usage: python3 tools/intro-fonts.py <fontsource ibm-plex-sans-kr package dir> <fontsource ibm-plex-mono package dir>
(npm pack @fontsource/ibm-plex-sans-kr@5.1.0 @fontsource/ibm-plex-mono@5.1.0; the same OFL files Google Fonts serves.)
Run it again after changing the page's words: a character the page did not have before is otherwise missing."""
import re, sys, shutil, pathlib, html, tempfile
from fontTools.ttLib import TTFont
from fontTools.subset import Subsetter, Options
from fontTools.merge import Merger
here = pathlib.Path(__file__).resolve().parent.parent / 'public' / 'intro'
kr, mono = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
text = html.unescape(re.sub(r'<[^>]+>', ' ', (here / 'index.html').read_text(encoding='utf-8')))
chars = {ord(c) for c in text} | set(range(0x20, 0x7f))
def ranges(s):
    for part in s.split(','):
        a, _, b = part.strip()[2:].partition('-')
        yield int(a, 16), int(b or a, 16)
out = here / 'fonts'; shutil.rmtree(out, ignore_errors=True); out.mkdir()
tmp = pathlib.Path(tempfile.mkdtemp())
css = []
def build(pkg, cssname, family, name, weight):
    parts = []
    for b in re.findall(r'@font-face \{(.*?)\}', (pkg / cssname).read_text(), re.S):
        ur = re.search(r'unicode-range: ([^;]+);', b)
        need = sorted(c for c in chars if not ur or any(a <= c <= z for a, z in ranges(ur.group(1))))
        if not need:
            continue
        f = re.search(r'url\(\./files/([^)]+\.woff2)\)', b).group(1)
        opts = Options(); opts.layout_features = ['*']; opts.notdef_outline = True
        font = TTFont(pkg / 'files' / f); sub = Subsetter(opts); sub.populate(unicodes=need); sub.subset(font)
        font.flavor = None; p = tmp / f.replace('.woff2', '.ttf'); font.save(p); parts.append(str(p))
    font = Merger().merge(parts) if len(parts) > 1 else TTFont(parts[0])
    font.flavor = 'woff2'; font.save(out / f'{name}-{weight}.woff2')
    css.append(f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: {weight}; font-display: swap; src: url(fonts/{name}-{weight}.woff2) format('woff2'); }}")
for w in ('400', '500'):
    build(kr, f'{w}.css', 'IBM Plex Sans KR', 'plex-sans-kr', w)
    build(mono, f'{w}.css', 'IBM Plex Mono', 'plex-mono', w)
(here / 'fonts.css').write_text('/* generated by frontend/tools/intro-fonts.py: only the characters this page uses */\n' + '\n'.join(css) + '\n')
print(len(list(out.iterdir())), 'files', sum(p.stat().st_size for p in out.iterdir()) // 1024, 'KB')
